# df_calibration.R — calibration grid for the mixed-model denominator-df reference.
#
# Measures, per cell, how three reference distributions for the fixed-effect
# test behave when the number of clusters is small:
#   * z   — MCPower's Wald z (df_method = "asymptotic")
#   * bw  — MCPower's default between-within t (df_method = "between_within";
#           a collapsed fit, every variance component at zero, is referred to
#           the residual df N − p instead)
#   * sat — lmerTest Satterthwaite t (external reference; LMM cells only —
#           lmerTest has no GLMM support, so logit cells carry z and bw only)
#
# Cells: g clusters in {5, 10, 20, 30, 50} × ICC in {0.1, 0.5} × family in
# {lme, logit}, balanced clusters of 20 observations (N = 20 g). Every cell fits
# `y ~ x + z + (1|g)` with x observation-level (within df) and z cluster-level
# (between df), so one draw serves both target levels and the joint test.
#
# Per cell, all reported, none gated:
#   1. Type-I error at effect = 0, per arm and target (per-draw, K draws).
#      The three arms score the SAME generated bytes: MCPower's load_data()
#      gives the engine statistic and per-arm critical value, lmerTest refits
#      the same design/outcome/cluster ids.
#   2. Power at the alternative along an N grid (fixed g, growing cluster
#      size), per arm — the first grid N reaching 80% is the recommended
#      sample size under that arm. Same per-draw scoring on identical bytes.
#   3. Joint test of {x, z} at the null: engine z vs bw from find_power
#      (its own draw stream — the per-draw path exposes no joint statistic),
#      lmerTest joint Satterthwaite F from the per-draw refits. LMM cells only.
#
# Sanity tripwire (printed, not gated): power under bw <= power under z on
# every grid point — a larger critical value can only lower power.
#
# Run from mcpower/validation/:
#   DFCAL_K=10000 DFCAL_CORES=12 Rscript df_calibration.R
# Env knobs: DFCAL_K (type-I draws per cell, default 10000), DFCAL_K_N (draws
# per N-grid point, default = DFCAL_K), DFCAL_CORES (forked workers for the
# per-draw loops), DFCAL_FAMILIES ("lme,logit"), DFCAL_G ("5,10,20,30,50").
# Writes data/df_calibration.rds (everything) and data/df_calibration.csv
# (the flat per-cell table); validation_df_calibration.rmd renders both.

suppressPackageStartupMessages({
  library(mcpower)
  library(lmerTest)
})

K        <- as.integer(Sys.getenv("DFCAL_K", "10000"))
K_N      <- as.integer(Sys.getenv("DFCAL_K_N", as.character(K)))
CORES    <- as.integer(Sys.getenv("DFCAL_CORES", "1"))
FAMILIES <- trimws(strsplit(Sys.getenv("DFCAL_FAMILIES", "lme,logit"), ",")[[1]])
G_VALUES <- as.integer(trimws(strsplit(Sys.getenv("DFCAL_G", "5,10,20,30,50"), ",")[[1]]))
ICCS     <- c(0.1, 0.5)
CLUSTER_SIZE <- 20L
# N grid as cluster sizes (N = g × size); g stays fixed inside a cell so the
# between df never moves along the grid — that is the regime under test.
SIZE_GRID <- c(5L, 10L, 20L, 30L, 40L, 60L, 80L, 120L, 160L, 200L)
ALPHA    <- 0.05
TARGET_POWER <- 0.80
# Alternative effect: medium continuous 0.25 for the LMM; the OR-1.5 anchor
# log(1.5) = 0.405 for the logit GLMM (the effect-size benchmark table).
ALT_EFFECT <- c(lme = 0.25, logit = 0.405)
BASELINE_P <- 0.5
BASE_SEED  <- 90000L
Z_CRIT <- stats::qnorm(1 - ALPHA / 2)

cat(sprintf("df calibration — K = %d (type-I), K_N = %d (per N point), cores = %d, families = %s, g = %s\n\n",
            K, K_N, CORES, paste(FAMILIES, collapse = "/"), paste(G_VALUES, collapse = "/")))

# ---- cells -------------------------------------------------------------------

CELLS <- list()
for (fam in FAMILIES) for (g in G_VALUES) for (icc in ICCS) {
  CELLS[[length(CELLS) + 1L]] <- list(
    label = sprintf("%s_g%d_icc%g", fam, g, icc),
    family = fam, g = g, icc = icc,
    n = g * CLUSTER_SIZE,
    # Spacing must exceed every seed a cell consumes (K type-I draws plus the
    # N-grid runs at cell$seed + 100000 * i) so no two cells share a draw.
    seed = BASE_SEED + 10000000L * length(CELLS)
  )
}

# One MCPowerDebug per (cell, effect, n). x is observation-level, z is declared
# cluster-level so bw gives it the between df (g − 2: intercept + z).
build_cell_model <- function(cell, effect, n) {
  m <- MCPowerDebug$new("y ~ x + z + (1|g)", family = cell$family,
                        debug_n = as.integer(n), debug_n_sims = 1L)
  if (cell$family == "logit") m$set_baseline_probability(BASELINE_P)
  m$set_effects(sprintf("x=%g, z=%g", effect, effect))
  m$set_cluster("g", ICC = cell$icc, n_clusters = cell$g, cluster_level_vars = "z")
  m
}

# Targets are design columns 2 (x) and 3 (z); load_data() returns them in
# target order, so targets[[1]] is x and targets[[2]] is z.
TARGETS <- c("x", "z")
L_JOINT <- rbind(c(0, 1, 0), c(0, 0, 1))

# lmerTest refit on the engine's bytes: design already carries the intercept
# column, so the fit goes through the origin on the matrix (as fit_sota does).
# Returns Satterthwaite p-values for x, z and the joint F, or NULL on failure.
sat_fit <- function(d) {
  df <- as.data.frame(d$design)
  names(df) <- c("V1", "V2", "V3")
  df$.y <- d$outcome
  df$.g <- factor(d$cluster_ids)
  fit <- tryCatch(
    suppressMessages(lmerTest::lmer(.y ~ 0 + V1 + V2 + V3 + (1 | .g), data = df, REML = TRUE,
                                    control = lme4::lmerControl(calc.derivs = FALSE))),
    error = function(e) NULL)
  if (is.null(fit)) return(NULL)
  cs <- tryCatch(stats::coef(summary(fit)), error = function(e) NULL)
  jt <- tryCatch(lmerTest::contest(fit, L = L_JOINT, joint = TRUE), error = function(e) NULL)
  if (is.null(cs) || is.null(jt)) return(NULL)
  p <- cs[c("V2", "V3"), "Pr(>|t|)"]
  if (any(!is.finite(p))) return(NULL)
  list(p = as.numeric(p), p_joint = as.numeric(jt[["Pr(>F)"]]), ddf = as.numeric(cs[c("V2", "V3"), "df"]))
}

pluck <- function(targets, field) vapply(targets, function(t) t[[field]], numeric(1))

# Per-draw scoring over draws [k_from, k_to]. Draw k is fully determined by
# .debug_seed = base_seed + k, so any split across workers recombines exactly.
# A draw counts only when every arm scored it (engine converged; lmerTest fit
# succeeded on LMM cells) — that keeps the arms on identical draws.
score_range <- function(cell, effect, n, base_seed, k_from, k_to) {
  m <- build_cell_model(cell, effect, n)
  rej_z <- rej_bw <- rej_sat <- c(0L, 0L)
  rej_sat_joint <- 0L
  sat_ddf <- c(0, 0)
  # bw df is g - 2 / N - g - 1 on a live fit and N - p on a collapsed LMM fit,
  # summed like the Satterthwaite df and reported as a mean. A collapsed GLMM
  # fit falls to Wald z and carries no df, so the mean runs over the draws that
  # had one (bw_t_n), not over every kept draw.
  bw_ddf <- c(0, 0)
  bw_t_n <- c(0L, 0L)
  collapsed <- 0L
  kept <- skipped <- 0L
  for (k in seq.int(k_from, k_to)) {
    m$.debug_seed <- as.numeric(base_seed + k)
    d  <- tryCatch(m$create_data(), error = function(e) NULL)
    fz <- if (is.null(d)) NULL else tryCatch(m$load_data(d, df_method = "asymptotic"), error = function(e) NULL)
    fb <- if (is.null(d)) NULL else tryCatch(m$load_data(d, df_method = "between_within"), error = function(e) NULL)
    if (is.null(fz) || is.null(fb) || !isTRUE(fz$converged) || !isTRUE(fb$converged)) {
      skipped <- skipped + 1L; next
    }
    stat   <- pluck(fz$targets, "statistic")
    crit_z <- pluck(fz$targets, "critical_value")
    crit_b <- pluck(fb$targets, "critical_value")
    if (any(!is.finite(c(stat, crit_z, crit_b)))) { skipped <- skipped + 1L; next }
    sat <- NULL
    if (cell$family == "lme") {
      sat <- sat_fit(d)
      if (is.null(sat)) { skipped <- skipped + 1L; next }
    }
    kept   <- kept + 1L
    bw_df  <- vapply(fb$targets, function(t) if (length(t$df)) t$df[1] else NA_real_, numeric(1))
    bw_ddf <- bw_ddf + ifelse(is.na(bw_df), 0, bw_df)
    bw_t_n <- bw_t_n + as.integer(!is.na(bw_df))
    if (length(fb$variance_components) && all(fb$variance_components == 0)) collapsed <- collapsed + 1L
    rej_z  <- rej_z  + as.integer(abs(stat) > crit_z)
    rej_bw <- rej_bw + as.integer(abs(stat) > crit_b)
    if (!is.null(sat)) {
      rej_sat       <- rej_sat + as.integer(sat$p < ALPHA)
      rej_sat_joint <- rej_sat_joint + as.integer(sat$p_joint < ALPHA)
      sat_ddf       <- sat_ddf + sat$ddf
    }
    if (k %% 50L == 0L) gc(FALSE)
  }
  list(rej_z = rej_z, rej_bw = rej_bw, rej_sat = rej_sat, rej_sat_joint = rej_sat_joint,
       sat_ddf = sat_ddf, bw_ddf = bw_ddf, bw_t_n = bw_t_n, collapsed = collapsed,
       kept = kept, skipped = skipped)
}

# K draws of one (cell, effect, n), single-core or fanned across CORES forked
# workers (the per-draw path is single-threaded, so forking is safe). Jobs are
# short chunks rather than K / CORES slabs: lme4 objects leave heap behind in a
# long-lived worker, and a fork only returns its memory when it exits.
CHUNK <- 250L
score_draws <- function(cell, effect, n, base_seed, K) {
  if (CORES <= 1L) return(score_range(cell, effect, n, base_seed, 1L, K))
  starts <- seq.int(1L, K, by = CHUNK)
  jobs <- lapply(starts, function(a) c(a, min(a + CHUNK - 1L, K)))
  parts <- parallel::mclapply(jobs, function(r)
    score_range(cell, effect, n, base_seed, r[1L], r[2L]),
    mc.cores = CORES, mc.preschedule = FALSE)
  bad <- vapply(parts, function(p) inherits(p, "try-error") || !is.list(p), logical(1))
  if (any(bad))
    stop(sprintf("mclapply worker failed (%s): %s", cell$label,
                 paste(unlist(parts[bad]), collapse = " | ")))
  fields <- names(parts[[1L]])
  stats::setNames(lapply(fields, function(f) Reduce(`+`, lapply(parts, `[[`, f))), fields)
}

# Wilson interval on a rejection count — the same interval MCPower reports.
wilson <- function(x, n, z = Z_CRIT) {
  if (n == 0L) return(c(NA_real_, NA_real_))
  p <- x / n; den <- 1 + z^2 / n
  ctr <- (p + z^2 / (2 * n)) / den
  hw  <- z * sqrt(p * (1 - p) / n + z^2 / (4 * n^2)) / den
  c(ctr - hw, ctr + hw)
}

# Engine joint Wald rate (its own draw stream, n_sims = K) for one df_method.
joint_engine_rate <- function(cell, effect, n, df_method, seed, K) {
  m <- MCPower$new("y ~ x + z + (1|g)", family = cell$family)
  m$set_effects(sprintf("x=%g, z=%g", effect, effect))
  m$set_cluster("g", ICC = cell$icc, n_clusters = cell$g, cluster_level_vars = "z")
  r <- m$find_power(sample_size = n, target_test = "x, z", n_sims = K, seed = seed,
                    df_method = df_method, verbose = FALSE, progress_callback = FALSE)
  r$estimator_extras$joint_uncorrected_rate
}

# ---- run ---------------------------------------------------------------------

rows <- list()       # flat per-cell table (one row per cell × arm × target)
curves <- list()     # per-cell power curves along the N grid
t_start <- Sys.time()

# Checkpoint: finished cells are saved after each cell and reused on the next
# start with the same settings, so an interrupted run resumes instead of
# starting over. `guard` is everything that defines a cell's draws and scoring
# besides its label; a checkpoint written under different settings (or a
# different engine build) is discarded. Removed once the run completes.
PARTIAL <- file.path("data", "df_calibration.partial.rds")
guard <- list(K = K, K_N = K_N, cluster_size = CLUSTER_SIZE, size_grid = SIZE_GRID,
              alpha = ALPHA, target_power = TARGET_POWER, alt_effect = ALT_EFFECT,
              baseline_p = BASELINE_P, base_seed = BASE_SEED,
              mcpower = as.character(utils::packageVersion("mcpower")))
done <- if (file.exists(PARTIAL)) readRDS(PARTIAL) else list(guard = guard, cells = list())
if (!identical(done$guard, guard)) done <- list(guard = guard, cells = list())

for (cell in CELLS) {
  cat(sprintf("[%s] N = %d ... ", cell$label, cell$n)); flush.console()
  if (!is.null(done$cells[[cell$label]])) {
    d <- done$cells[[cell$label]]
    rows <- c(rows, d$rows); curves[[cell$label]] <- d$curve
    cat("resumed from checkpoint\n"); next
  }
  n_rows_before <- length(rows)
  t0 <- Sys.time()
  arms <- if (cell$family == "lme") c("z", "bw", "sat") else c("z", "bw")

  # 1. type-I at the null
  null <- score_draws(cell, 0, cell$n, cell$seed, K)

  # 3. joint at the null (LMM only — the GLMM result carries no joint rate)
  joint <- if (cell$family == "lme") list(
    z   = joint_engine_rate(cell, 0, cell$n, "asymptotic",     cell$seed, K),
    bw  = joint_engine_rate(cell, 0, cell$n, "between_within", cell$seed, K),
    sat = null$rej_sat_joint / null$kept
  ) else NULL

  # 2. power along the N grid at the alternative
  eff  <- ALT_EFFECT[[cell$family]]
  grid <- lapply(seq_along(SIZE_GRID), function(i) {
    n_i <- cell$g * SIZE_GRID[i]
    s <- score_draws(cell, eff, n_i, cell$seed + 100000L * i, K_N)
    data.frame(label = cell$label, n = n_i, cluster_size = SIZE_GRID[i], kept = s$kept,
               skipped = s$skipped,
               power_z_x = s$rej_z[1] / s$kept,  power_z_z = s$rej_z[2] / s$kept,
               power_bw_x = s$rej_bw[1] / s$kept, power_bw_z = s$rej_bw[2] / s$kept,
               power_sat_x = if (cell$family == "lme") s$rej_sat[1] / s$kept else NA_real_,
               power_sat_z = if (cell$family == "lme") s$rej_sat[2] / s$kept else NA_real_)
  })
  grid <- do.call(rbind, grid)
  curves[[cell$label]] <- grid

  first_n <- function(col) { i <- which(grid[[col]] >= TARGET_POWER); if (length(i)) grid$n[i[1]] else NA_integer_ }
  rate <- function(x) x / null$kept
  for (arm in arms) for (ti in seq_along(TARGETS)) {
    rej <- switch(arm, z = null$rej_z, bw = null$rej_bw, sat = null$rej_sat)[ti]
    ci  <- wilson(rej, null$kept)
    rows[[length(rows) + 1L]] <- data.frame(
      label = cell$label, family = cell$family, g = cell$g, icc = cell$icc, n = cell$n,
      arm = arm, target = TARGETS[ti],
      level = if (TARGETS[ti] == "z") "between" else "within",
      df = switch(arm, z = Inf, bw = null$bw_ddf[ti] / null$bw_t_n[ti], sat = null$sat_ddf[ti] / null$kept),
      collapsed_share = null$collapsed / null$kept,
      type1 = rate(rej), type1_lo = ci[1], type1_hi = ci[2],
      power_at_n = grid[[sprintf("power_%s_%s", arm, TARGETS[ti])]][grid$n == cell$n],
      n_at_80 = first_n(sprintf("power_%s_%s", arm, TARGETS[ti])),
      joint_type1 = if (!is.null(joint)) joint[[arm]] else NA_real_,
      kept = null$kept, skipped = null$skipped, seed = cell$seed,
      stringsAsFactors = FALSE)
  }
  el <- as.numeric(difftime(Sys.time(), t0, units = "secs"))
  tI <- vapply(arms, function(a) paste(sprintf("%.1f", 100 * rate(switch(a, z = null$rej_z, bw = null$rej_bw, sat = null$rej_sat))), collapse = "/"), character(1))
  cat(sprintf("type-I x/z %% — %s; kept %d, skipped %d, collapsed %.1f%%; %.0fs\n",
              paste(sprintf("%s %s", arms, tI), collapse = ", "), null$kept, null$skipped,
              100 * null$collapsed / null$kept, el))
  done$cells[[cell$label]] <- list(rows = rows[seq.int(n_rows_before + 1L, length(rows))], curve = grid)
  saveRDS(done, PARTIAL)
}

table <- do.call(rbind, rows)

# Sanity tripwire: bw power <= z power on every grid point (printed, not gated).
curve_all <- do.call(rbind, curves)
sanity_ok <- isTRUE(all(curve_all$power_bw_x <= curve_all$power_z_x & curve_all$power_bw_z <= curve_all$power_z_z))
cat(sprintf("\nSanity (bw power <= z power on every grid point): %s\n", if (sanity_ok) "OK" else "VIOLATED"))

out <- list(
  settings = list(K = K, K_N = K_N, cluster_size = CLUSTER_SIZE, size_grid = SIZE_GRID,
                  alpha = ALPHA, target_power = TARGET_POWER, alt_effect = ALT_EFFECT,
                  baseline_p = BASELINE_P, base_seed = BASE_SEED,
                  mcpower = as.character(utils::packageVersion("mcpower")),
                  lmerTest = as.character(utils::packageVersion("lmerTest")),
                  lme4 = as.character(utils::packageVersion("lme4")),
                  run_at = format(t_start, "%Y-%m-%d %H:%M:%S"),
                  elapsed_sec = as.numeric(difftime(Sys.time(), t_start, units = "secs"))),
  table = table, curves = curve_all, sanity_ok = sanity_ok
)
saveRDS(out, file.path("data", "df_calibration.rds"))
utils::write.csv(table, file.path("data", "df_calibration.csv"), row.names = FALSE)
if (file.exists(PARTIAL)) invisible(file.remove(PARTIAL))
cat(sprintf("Wrote data/df_calibration.rds and data/df_calibration.csv (%.0f s total)\n",
            out$settings$elapsed_sec))
