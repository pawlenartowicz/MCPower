# The earlier run's table with its MCPower rows replaced by `table`, in the
# earlier row order. `keep` names columns of those rows that only the R refits
# can recompute.
join_reference <- function(table, old, keep = character()) {
  key <- function(t) paste(t$label, t$arm, t$target)
  i <- match(key(old), key(table))
  mc <- !is.na(i)
  if (sum(mc) != nrow(table)) stop(sprintf("%s does not match this grid", REFERENCE_FROM))
  joined <- old
  cols <- setdiff(names(table), keep)
  joined[mc, cols] <- table[i[mc], cols]
  moved <- abs(joined$type1[mc] - old$type1[mc])
  cat(sprintf("R arms reused from %s; MCPower arms moved on %d of %d rows, largest |type1 change| %.4f\n",
              REFERENCE_FROM, sum(moved > 0), length(moved), max(moved)))
  joined
}

# ---- random-slope grid (DFCAL_GRID=slopes) ----------------------------------
#
# Cells: g clusters in {5, 10, 20, 30, 60} × cluster size m in {8, 20} × slope
# variance in {.05, .10, .30}, ICC .3 (the intercept share, as in Example 2 of
# the paper). Every cell fits `y ~ x * w + (1 + x | g)`: x varies within
# clusters and has a random slope, w is binary and declared cluster-level, so
# the two targets are a within-cluster effect with a random slope (x) and a
# cross-level interaction (x:w). Effects x = 0, x:w = 0 (the null), w = 0.3.
# Arms on the SAME generated bytes per draw:
#   * bw   — MCPower, df_method = "between_within"
#   * sat  — MCPower, df_method = "satterthwaite"
#   * auto — MCPower's default (contract default, no override); on these cells
#            it must equal sat, and every draw where it does not is counted
#   * z    — Wald z on MCPower's statistic (the asymptotic reference)
#   * lmertest — lmerTest Satterthwaite t (refit of the same design matrix)
#   * kr   — Kenward–Roger (pbkrtest::vcovAdj on the same lmerTest fit)
# MCPower arms score draws 1..DFCAL_SLOPE_K (default 10,000); the R arms score
# draws 1..DFCAL_SLOPE_K_R (default 4,000) of the same stream, and
# type1_shared gives each MCPower arm's rate on exactly the draws the R arms
# scored. A draw counts for the MCPower arms when all three MCPower fits
# converged; it counts for the R arms when it also has a successful lmerTest
# fit (and, for kr, a finite KR test). Joint test of {x, x:w} at the null:
# MCPower arms from find_power on its own draw stream (n_sims = DFCAL_SLOPE_K,
# the existing grid's convention), lmerTest joint F and the KR F on the
# per-draw refits. Nothing is gated.
# Env knobs: DFCAL_SLOPE_K, DFCAL_SLOPE_K_R, DFCAL_SLOPE_G ("5,10,20,30,60"),
# DFCAL_SLOPE_M ("8,20"), DFCAL_SLOPE_VAR (".05,.1,.3"), DFCAL_SLOPE_KR_M
# (cluster sizes on which the KR arm runs, default "8,20"), DFCAL_CORES.
# Writes data/df_calibration_slopes.rds and data/df_calibration_slopes.csv;
# data/df_calibration.{rds,csv} (the intercept grid) are not touched.
#   DFCAL_GRID=slopes DFCAL_CORES=4 Rscript df_calibration.R
if (identical(Sys.getenv("DFCAL_GRID", "intercept"), "slopes")) local({
  suppressPackageStartupMessages(library(pbkrtest))
  num_env <- function(name, default) as.numeric(trimws(strsplit(Sys.getenv(name, default), ",")[[1]]))
  SK    <- as.integer(Sys.getenv("DFCAL_SLOPE_K", "10000"))
  SK_R  <- as.integer(Sys.getenv("DFCAL_SLOPE_K_R", "4000"))
  SG    <- as.integer(num_env("DFCAL_SLOPE_G", "5,10,20,30,60"))
  SM    <- as.integer(num_env("DFCAL_SLOPE_M", "8,20"))
  SVAR  <- num_env("DFCAL_SLOPE_VAR", ".05,.1,.3")
  KR_M  <- as.integer(num_env("DFCAL_SLOPE_KR_M", "8,20"))
  S_ICC <- 0.3
  S_SEED <- 50000000L
  S_TARGETS <- c("x", "x:w")
  S_TIDX <- c(1L, 3L)          # design columns: intercept, x, w, x:w (0-based 1 and 3)
  S_L <- rbind(c(0, 1, 0, 0), c(0, 0, 0, 1))
  CH <- 250L
  cat(sprintf("df calibration, random-slope grid — K = %d (MCPower), K_R = %d (R arms), cores = %d, g = %s, m = %s, slope var = %s, KR on m = %s\n\n",
              SK, SK_R, CORES, paste(SG, collapse = "/"), paste(SM, collapse = "/"),
              paste(SVAR, collapse = "/"), paste(KR_M, collapse = "/")))

  cells <- list()
  for (g in SG) for (m in SM) for (v in SVAR) cells[[length(cells) + 1L]] <- list(
    label = sprintf("slope_g%d_m%d_v%g", g, m, v), g = g, m = m, slope_var = v, n = g * m,
    seed = S_SEED + 100000L * length(cells))

  set_cell <- function(mod, cell) {
    mod$set_variable_type("w=binary")
    mod$set_effects("x=0, w=0.3, x:w=0")
    mod$set_cluster("g", ICC = S_ICC, n_clusters = cell$g, cluster_level_vars = "w",
                    random_slopes = list(list(predictor = "x", variance = cell$slope_var)))
    mod
  }

  pick <- function(fit) fit$targets[match(S_TIDX, vapply(fit$targets, `[[`, 0L, "target_index"))]

  r_fit <- function(d, kr) {
    X <- d$design
    df <- data.frame(V1 = X[, 1], V2 = X[, 2], V3 = X[, 3], V4 = X[, 4], .y = d$outcome,
                     .g = factor(d$cluster_ids))
    fit <- tryCatch(suppressWarnings(suppressMessages(
      lmerTest::lmer(.y ~ 0 + V1 + V2 + V3 + V4 + (1 + V2 | .g), data = df, REML = TRUE,
                     control = lme4::lmerControl(calc.derivs = FALSE)))), error = function(e) NULL)
    if (is.null(fit)) return(NULL)
    cs <- tryCatch(stats::coef(summary(fit)), error = function(e) NULL)
    if (is.null(cs) || nrow(cs) != 4L || !all(c("df", "Pr(>|t|)") %in% colnames(cs))) return(NULL)
    p <- cs[c("V2", "V4"), "Pr(>|t|)"]
    if (any(!is.finite(p))) return(NULL)
    jt <- tryCatch(lmerTest::contest(fit, L = S_L, joint = TRUE), error = function(e) NULL)
    out <- list(p = as.numeric(p), ddf = as.numeric(cs[c("V2", "V4"), "df"]),
                p_joint = if (is.null(jt)) NA_real_ else as.numeric(jt[["Pr(>F)"]]),
                singular = lme4::isSingular(fit),
                kr_p = c(NA_real_, NA_real_), kr_ddf = c(NA_real_, NA_real_), kr_p_joint = NA_real_)
    if (kr) {
      kr_res <- tryCatch({
        # Keep the attributes vcovAdj attaches (P, W): Lb_ddf and the KR F read them.
        Va <- pbkrtest::vcovAdj(fit)
        V0 <- stats::vcov(fit)
        Vm <- as.matrix(Va)
        b  <- lme4::fixef(fit)
        kp <- kd <- numeric(2)
        for (i in 1:2) {
          j <- c(2L, 4L)[i]
          Lj <- matrix(0, 1, 4); Lj[1, j] <- 1
          kd[i] <- pbkrtest::Lb_ddf(Lj, V0, Va)
          kp[i] <- 2 * stats::pt(-abs(b[j] / sqrt(Vm[j, j])), kd[i])
        }
        st <- pbkrtest:::.KR_adjust(Va, Phi = V0, S_L, beta = b, betaH = 0)
        fin <- pbkrtest:::.finalizeKR(lapply(st, c))
        list(p = kp, ddf = kd, p_joint = as.numeric(fin$test["Ftest", "p.value"]))
      }, error = function(e) NULL)
      if (!is.null(kr_res) && all(is.finite(kr_res$p))) {
        out$kr_p <- kr_res$p; out$kr_ddf <- kr_res$ddf; out$kr_p_joint <- kr_res$p_joint
      }
    }
    out
  }

  # One row per draw. Draw k is fully determined by .debug_seed = cell$seed + k.
  score_slope_range <- function(cell, k_from, k_to) {
    mod <- set_cell(MCPowerDebug$new("y ~ x * w + (1 + x|g)", family = "lme",
                                     debug_n = as.integer(cell$n), debug_n_sims = 1L), cell)
    kr <- cell$m %in% KR_M
    rows <- vector("list", k_to - k_from + 1L)
    for (k in seq.int(k_from, k_to)) {
      mod$.debug_seed <- as.numeric(cell$seed + k)
      row <- c(k = k, mc_ok = 0, stat_x = NA, stat_xw = NA, crit_bw_x = NA, crit_bw_xw = NA,
               crit_sat_x = NA, crit_sat_xw = NA, crit_auto_x = NA, crit_auto_xw = NA,
               df_bw_x = NA, df_bw_xw = NA, df_sat_x = NA, df_sat_xw = NA, auto_neq_sat = NA,
               stat_neq = NA, mc_singular = NA, r_ok = NA, lt_p_x = NA, lt_p_xw = NA,
               lt_df_x = NA, lt_df_xw = NA, lt_p_joint = NA, lt_singular = NA,
               kr_p_x = NA, kr_p_xw = NA, kr_df_x = NA, kr_df_xw = NA, kr_p_joint = NA)
      d  <- tryCatch(mod$create_data(), error = function(e) NULL)
      fl <- if (is.null(d)) NULL else lapply(list(bw = "between_within", sat = "satterthwaite", auto = NULL),
        function(dm) tryCatch(mod$load_data(d, df_method = dm), error = function(e) NULL))
      ok <- !is.null(fl) && all(vapply(fl, function(f) !is.null(f) && isTRUE(f$converged), logical(1)))
      if (ok) {
        tb <- pick(fl$bw); ts <- pick(fl$sat); ta <- pick(fl$auto)
        g1 <- function(t, f) vapply(t, function(x) { v <- x[[f]]; if (length(v)) v[[1]] else Inf }, numeric(1))
        st <- g1(tb, "statistic")
        vc <- unlist(fl$auto$variance_components)[1:2]
        rc <- unlist(fl$auto$re_corr)
        row[c("mc_ok", "stat_x", "stat_xw")] <- c(1, st)
        row[c("crit_bw_x", "crit_bw_xw")]   <- g1(tb, "critical_value")
        row[c("crit_sat_x", "crit_sat_xw")] <- g1(ts, "critical_value")
        row[c("crit_auto_x", "crit_auto_xw")] <- g1(ta, "critical_value")
        row[c("df_bw_x", "df_bw_xw")]   <- g1(tb, "df")
        row[c("df_sat_x", "df_sat_xw")] <- g1(ts, "df")
        row["auto_neq_sat"] <- as.numeric(!identical(g1(ta, "critical_value"), g1(ts, "critical_value")) ||
                                          !identical(g1(ta, "statistic"), g1(ts, "statistic")))
        row["stat_neq"] <- as.numeric(!identical(st, g1(ts, "statistic")))
        row["mc_singular"] <- as.numeric(any(vc == 0) || (length(rc) == 1L && abs(rc) > 1 - 1e-6))
        if (REFIT && k <= SK_R) {
          r <- r_fit(d, kr)
          row["r_ok"] <- as.numeric(!is.null(r))
          if (!is.null(r)) {
            row[c("lt_p_x", "lt_p_xw")] <- r$p
            row[c("lt_df_x", "lt_df_xw")] <- r$ddf
            row["lt_p_joint"] <- r$p_joint
            row["lt_singular"] <- as.numeric(r$singular)
            row[c("kr_p_x", "kr_p_xw")] <- r$kr_p
            row[c("kr_df_x", "kr_df_xw")] <- r$kr_ddf
            row["kr_p_joint"] <- r$kr_p_joint
          }
        }
      }
      rows[[k - k_from + 1L]] <- row
      if (k %% 50L == 0L) gc(FALSE)
    }
    do.call(rbind, rows)
  }

  score_slope_cell <- function(cell) {
    starts <- seq.int(1L, SK, by = CH)
    jobs <- lapply(starts, function(a) c(a, min(a + CH - 1L, SK)))
    parts <- parallel::mclapply(jobs, function(r) score_slope_range(cell, r[1L], r[2L]),
                                mc.cores = max(1L, CORES), mc.preschedule = FALSE)
    bad <- vapply(parts, function(p) inherits(p, "try-error") || !is.matrix(p), logical(1))
    if (any(bad)) stop(sprintf("mclapply worker failed (%s): %s", cell$label,
                               paste(unlist(parts[bad]), collapse = " | ")))
    D <- as.data.frame(do.call(rbind, parts))
    D[order(D$k), ]
  }

  joint_rate <- function(cell, df_method) {
    mod <- set_cell(MCPower$new("y ~ x * w + (1 + x|g)", family = "lme"), cell)
    args <- list(sample_size = cell$n, target_test = "x, x:w", n_sims = SK, seed = cell$seed,
                 verbose = FALSE, progress_callback = FALSE)
    if (!is.null(df_method)) args$df_method <- df_method
    suppressWarnings(do.call(mod$find_power, args))$estimator_extras$joint_uncorrected_rate
  }

  rate_ci <- function(x) {
    x <- x[!is.na(x)]; n <- length(x)
    if (!n) return(c(NA, NA, NA, NA, 0))
    p <- mean(x); w <- wilson(sum(x), n)
    c(p, sqrt(p * (1 - p) / n), w[1], w[2], n)
  }
  wilson <- function(x, n, z = Z_CRIT) {
    p <- x / n; den <- 1 + z^2 / n
    ctr <- (p + z^2 / (2 * n)) / den
    hw  <- z * sqrt(p * (1 - p) / n + z^2 / (4 * n^2)) / den
    c(ctr - hw, ctr + hw)
  }

  PART <- file.path("data", "df_calibration_slopes.partial.rds")
  guard <- list(SK = SK, SK_R = SK_R, KR_M = KR_M, icc = S_ICC, seed = S_SEED, alpha = ALPHA,
                mcpower = as.character(utils::packageVersion("mcpower")),
                reference_from = REFERENCE_FROM)
  done <- if (file.exists(PART)) readRDS(PART) else list(guard = guard, cells = list())
  if (!identical(done$guard, guard)) done <- list(guard = guard, cells = list())
  t_start <- Sys.time()
  rows <- list()
  for (cell in cells) {
    cat(sprintf("[%s] N = %d ... ", cell$label, cell$n)); flush.console()
    if (!is.null(done$cells[[cell$label]])) {
      rows <- c(rows, list(done$cells[[cell$label]])); cat("resumed from checkpoint\n"); next
    }
    t0 <- Sys.time()
    D <- score_slope_cell(cell)
    M <- D[D$mc_ok == 1, ]
    R <- M[!is.na(M$r_ok) & M$r_ok == 1, ]
    joint <- list(bw = joint_rate(cell, "between_within"), sat = joint_rate(cell, "satterthwaite"),
                  auto = joint_rate(cell, NULL), z = joint_rate(cell, "asymptotic"))
    out <- list()
    for (ti in 1:2) {
      sfx <- c("x", "xw")[ti]
      stat <- abs(M[[paste0("stat_", sfx)]]); stat_r <- abs(R[[paste0("stat_", sfx)]])
      mc_arm <- function(arm) {
        crit <- if (arm == "z") rep(Z_CRIT, nrow(M)) else M[[sprintf("crit_%s_%s", arm, sfx)]]
        crit_r <- if (arm == "z") rep(Z_CRIT, nrow(R)) else R[[sprintf("crit_%s_%s", arm, sfx)]]
        dfv <- switch(arm, z = Inf, bw = M[[paste0("df_bw_", sfx)]],
                      sat = M[[paste0("df_sat_", sfx)]], auto = M[[paste0("df_sat_", sfx)]])
        list(rej = as.numeric(stat > crit), rej_shared = as.numeric(stat_r > crit_r), df = dfv,
             fallback = if (arm %in% c("sat", "auto")) sum(!is.finite(dfv)) else 0L,
             joint = joint[[arm]], sing = M$mc_singular)
      }
      r_arm <- function(arm) {
        p  <- R[[sprintf("%s_p_%s", arm, sfx)]]
        dfv <- R[[sprintf("%s_df_%s", arm, sfx)]]
        pj <- R[[sprintf("%s_p_joint", arm)]]
        list(rej = as.numeric(p < ALPHA), rej_shared = NULL, df = dfv, fallback = 0L,
             joint = mean(pj < ALPHA, na.rm = TRUE), joint_n = sum(!is.na(pj)), sing = R$lt_singular)
      }
      arms <- list(bw = mc_arm("bw"), sat = mc_arm("sat"), auto = mc_arm("auto"), z = mc_arm("z"))
      if (REFIT) arms <- c(arms, list(lmertest = r_arm("lt"), kr = r_arm("kr")))
      for (a in names(arms)) {
        A <- arms[[a]]; rc <- rate_ci(A$rej)
        rs <- if (is.null(A$rej_shared)) c(NA, NA) else rate_ci(A$rej_shared)[1:2]
        jn <- if (!is.null(A$joint_n)) A$joint_n else SK
        out[[length(out) + 1L]] <- data.frame(
          label = cell$label, g = cell$g, cluster_size = cell$m, slope_var = cell$slope_var,
          icc = S_ICC, n = cell$n, arm = a, target = S_TARGETS[ti],
          level = if (ti == 1L) "within, random slope" else "cross-level interaction",
          df_median = if (rc[5] == 0) NA_real_ else if (all(!is.finite(A$df))) Inf
                      else stats::median(A$df[is.finite(A$df)]),
          df_fallback = A$fallback,
          singular_share = mean(A$sing, na.rm = TRUE),
          type1 = rc[1], se = rc[2], type1_lo = rc[3], type1_hi = rc[4], n_draws = rc[5],
          type1_shared = rs[1], se_shared = rs[2],
          joint_type1 = if (is.null(A$joint)) NA_real_ else A$joint,
          joint_se = if (is.null(A$joint) || is.na(A$joint)) NA_real_ else sqrt(A$joint * (1 - A$joint) / jn),
          kept = nrow(M), skipped = SK - nrow(M), r_kept = nrow(R),
          r_skipped = sum(M$k <= SK_R) - nrow(R),
          auto_neq_sat = sum(M$auto_neq_sat), seed = cell$seed, stringsAsFactors = FALSE)
      }
    }
    cell_rows <- do.call(rbind, out)
    if (sum(M$stat_neq) > 0) cat(sprintf("(statistic differs between bw and sat fits on %d draws) ", sum(M$stat_neq)))
    el <- as.numeric(difftime(Sys.time(), t0, units = "secs"))
    sh <- cell_rows[, c("arm", "target", "type1")]
    cat(sprintf("type-I x / x:w %% — %s; kept %d/%d, R kept %d, auto != sat on %d; %.0fs\n",
                paste(vapply(names(arms), function(a) sprintf("%s %s", a,
                  paste(sprintf("%.1f", 100 * sh$type1[sh$arm == a]), collapse = "/")), ""), collapse = ", "),
                nrow(M), SK, nrow(R), sum(M$auto_neq_sat), el))
    rows <- c(rows, list(cell_rows))
    done$cells[[cell$label]] <- cell_rows
    saveRDS(done, PART)
  }
  table <- do.call(rbind, rows)
  # The refits that failed were not saved per draw, so the shared-draw columns
  # stay as the earlier run scored them.
  reference <- if (REFIT) NULL else readRDS(REFERENCE_FROM)
  if (!REFIT) table <- join_reference(table, reference$table,
                                      keep = c("type1_shared", "se_shared", "r_kept", "r_skipped"))
  out <- list(
    reference = reference$settings,
    settings = list(K = SK, K_R = SK_R, g = SG, cluster_sizes = SM, slope_var = SVAR, kr_sizes = KR_M,
                    icc = S_ICC, alpha = ALPHA, base_seed = S_SEED,
                    formula = "y ~ x * w + (1 + x | g)", effects = "x=0, w=0.3, x:w=0",
