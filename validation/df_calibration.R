# df_calibration.R — calibration grid for the mixed-model denominator-df reference.
#
# Measures, per cell, how three reference distributions for the fixed-effect
# test behave when the number of clusters is small:
#   * z   — MCPower's Wald z (df_method = "asymptotic")
#   * bw  — MCPower's between-within t (df_method = "between_within", which the
#           default "auto" picks on these single-grouping intercept-only cells;
#           a collapsed fit, every variance component at zero, is referred to
#           the residual df N − p instead)
#   * sat — lmerTest Satterthwaite t (external reference; LMM cells only —
#           lmerTest has no GLMM support, so logit cells carry z and bw only)
#
# Cells: g clusters in {5, 10, 20, 30, 50} × ICC in {0.1, 0.5} × family in
# {lme, logit}, balanced clusters of 20 observations (N = 20 g). Every cell fits
# `y ~ x + z + (1|g)` with x observation-level (within df) and z cluster-level
# (between df), so one draw serves both target levels and the joint test.
#
# Per cell, all reported, none gated:
#   1. Type-I error at effect = 0, per arm and target (per-draw, K draws).
#      The three arms score the SAME generated bytes: MCPower's load_data()
#      gives the engine statistic and per-arm critical value, lmerTest refits
#      the same design/outcome/cluster ids.
#   2. Power at the alternative along an N grid (fixed g, growing cluster
#      size), per arm — the first grid N reaching 80% is the recommended
#      sample size under that arm. Same per-draw scoring on identical bytes.
#   3. Joint test of {x, z} at the null: engine z vs bw from find_power
#      (its own draw stream — the per-draw path exposes no joint statistic),
#      lmerTest joint Satterthwaite F from the per-draw refits. LMM cells only.
#
# Sanity tripwire (printed, not gated): power under bw <= power under z on
# every grid point — a larger critical value can only lower power.
#
# Run from mcpower/validation/:
#   DFCAL_K=10000 DFCAL_CORES=12 Rscript df_calibration.R
# Env knobs: DFCAL_K (type-I draws per cell, default 10000), DFCAL_K_N (draws
# per N-grid point, default = DFCAL_K), DFCAL_CORES (forked workers for the
# per-draw loops), DFCAL_FAMILIES ("lme,logit"), DFCAL_G ("5,10,20,30,50"),
# DFCAL_REFERENCE_FROM (the .rds of an earlier run of the same grid: no R refit
# runs, the R arms come from that file, and the recomputed MCPower arms are
# compared with it). A reused R arm stays paired with the MCPower arms only while
# the generated bytes are unchanged, which the printed "moved" line reports.
# Writes data/df_calibration.rds (everything) and data/df_calibration.csv
# (the flat per-cell table); validation_df_calibration.rmd renders both.
#
# DFCAL_GRID=slopes runs the random-slope grid instead (see the block below the
# settings): y ~ x * w + (1 + x | g) over clusters x cluster size x slope
# variance, arms between-within, Satterthwaite and auto (MCPower), Wald z,
# lmerTest and Kenward-Roger, written to data/df_calibration_slopes.{rds,csv}.

