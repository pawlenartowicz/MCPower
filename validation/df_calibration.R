# One MCPowerDebug per (cell, effect, n). x is observation-level, z is declared
# cluster-level so bw gives it the between df (g − 2: intercept + z).
build_cell_model <- function(cell, effect, n) {
  m <- MCPowerDebug$new("y ~ x + z + (1|g)", family = cell$family,
                        debug_n = as.integer(n), debug_n_sims = 1L)
  if (cell$family == "logit") m$set_baseline_probability(BASELINE_P)
  m$set_effects(sprintf("x=%g, z=%g", effect, effect))
  m$set_cluster("g", ICC = cell$icc, n_clusters = cell$g, cluster_level_vars = "z")
  m
}

# Targets are design columns 2 (x) and 3 (z); load_data() returns them in
# target order, so targets[[1]] is x and targets[[2]] is z.
TARGETS <- c("x", "z")
L_JOINT <- rbind(c(0, 1, 0), c(0, 0, 1))

# lmerTest refit on the engine's bytes: design already carries the intercept
# column, so the fit goes through the origin on the matrix (as fit_sota does).
# Returns Satterthwaite p-values for x, z and the joint F, or NULL on failure.
sat_fit <- function(d) {
  df <- as.data.frame(d$design)
  names(df) <- c("V1", "V2", "V3")
  df$.y <- d$outcome
  df$.g <- factor(d$cluster_ids)
  fit <- tryCatch(
    suppressMessages(lmerTest::lmer(.y ~ 0 + V1 + V2 + V3 + (1 | .g), data = df, REML = TRUE,
                                    control = lme4::lmerControl(calc.derivs = FALSE))),
    error = function(e) NULL)
  if (is.null(fit)) return(NULL)
  cs <- tryCatch(stats::coef(summary(fit)), error = function(e) NULL)
  jt <- tryCatch(lmerTest::contest(fit, L = L_JOINT, joint = TRUE), error = function(e) NULL)
  if (is.null(cs) || is.null(jt)) return(NULL)
  p <- cs[c("V2", "V3"), "Pr(>|t|)"]
  if (any(!is.finite(p))) return(NULL)
  list(p = as.numeric(p), p_joint = as.numeric(jt[["Pr(>F)"]]), ddf = as.numeric(cs[c("V2", "V3"), "df"]))
}

pluck <- function(targets, field) vapply(targets, function(t) t[[field]], numeric(1))

# Per-draw scoring over draws [k_from, k_to]. Draw k is fully determined by
# .debug_seed = base_seed + k, so any split across workers recombines exactly.
# A draw counts only when every arm scored it (engine converged; lmerTest fit
# succeeded on LMM cells) — that keeps the arms on identical draws.
score_range <- function(cell, effect, n, base_seed, k_from, k_to) {
  m <- build_cell_model(cell, effect, n)
  ws <- if (cell$family == "logit") GLMM_WALD_SE else NULL
  rej_z <- rej_bw <- rej_sat <- c(0L, 0L)
  rej_sat_joint <- 0L
  sat_ddf <- c(0, 0)
  # bw df is g - 2 / N - g - 1 on a live fit and N - p on a collapsed LMM fit,
  # summed like the Satterthwaite df and reported as a mean. A collapsed GLMM
  # fit falls to Wald z and carries no df, so the mean runs over the draws that
  # had one (bw_t_n), not over every kept draw.
  bw_ddf <- c(0, 0)
  bw_t_n <- c(0L, 0L)
  collapsed <- 0L
  kept <- skipped <- 0L
  for (k in seq.int(k_from, k_to)) {
    m$.debug_seed <- as.numeric(base_seed + k)
    d  <- tryCatch(m$create_data(), error = function(e) NULL)
    fz <- if (is.null(d)) NULL else tryCatch(m$load_data(d, wald_se = ws, df_method = "asymptotic"), error = function(e) NULL)
    fb <- if (is.null(d)) NULL else tryCatch(m$load_data(d, wald_se = ws, df_method = "between_within"), error = function(e) NULL)
    if (is.null(fz) || is.null(fb) || !isTRUE(fz$converged) || !isTRUE(fb$converged)) {
      skipped <- skipped + 1L; next
    }
    stat   <- pluck(fz$targets, "statistic")
    crit_z <- pluck(fz$targets, "critical_value")
    crit_b <- pluck(fb$targets, "critical_value")
    if (any(!is.finite(c(stat, crit_z, crit_b)))) { skipped <- skipped + 1L; next }
    sat <- NULL
    if (cell$family == "lme" && REFIT) {
      sat <- sat_fit(d)
      if (is.null(sat)) { skipped <- skipped + 1L; next }
    }
    kept   <- kept + 1L
    bw_df  <- vapply(fb$targets, function(t) if (length(t$df)) t$df[1] else NA_real_, numeric(1))
    bw_ddf <- bw_ddf + ifelse(is.na(bw_df), 0, bw_df)
    bw_t_n <- bw_t_n + as.integer(!is.na(bw_df))
    if (length(fb$variance_components) && all(fb$variance_components == 0)) collapsed <- collapsed + 1L
    rej_z  <- rej_z  + as.integer(abs(stat) > crit_z)
    rej_bw <- rej_bw + as.integer(abs(stat) > crit_b)
    if (!is.null(sat)) {
      rej_sat       <- rej_sat + as.integer(sat$p < ALPHA)
      rej_sat_joint <- rej_sat_joint + as.integer(sat$p_joint < ALPHA)
      sat_ddf       <- sat_ddf + sat$ddf
    }
    if (k %% 50L == 0L) gc(FALSE)
  }
  list(rej_z = rej_z, rej_bw = rej_bw, rej_sat = rej_sat, rej_sat_joint = rej_sat_joint,
       sat_ddf = sat_ddf, bw_ddf = bw_ddf, bw_t_n = bw_t_n, collapsed = collapsed,
       kept = kept, skipped = skipped)
}

# K draws of one (cell, effect, n), single-core or fanned across CORES forked
# workers (the per-draw path is single-threaded, so forking is safe). Jobs are
# short chunks rather than K / CORES slabs: lme4 objects leave heap behind in a
# long-lived worker, and a fork only returns its memory when it exits.
CHUNK <- 250L
score_draws <- function(cell, effect, n, base_seed, K) {
  if (CORES <= 1L) return(score_range(cell, effect, n, base_seed, 1L, K))
  starts <- seq.int(1L, K, by = CHUNK)
  jobs <- lapply(starts, function(a) c(a, min(a + CHUNK - 1L, K)))
  parts <- parallel::mclapply(jobs, function(r)
    score_range(cell, effect, n, base_seed, r[1L], r[2L]),
    mc.cores = CORES, mc.preschedule = FALSE)
  bad <- vapply(parts, function(p) inherits(p, "try-error") || !is.list(p), logical(1))
  if (any(bad))
    stop(sprintf("mclapply worker failed (%s): %s", cell$label,
                 paste(unlist(parts[bad]), collapse = " | ")))
  fields <- names(parts[[1L]])
  stats::setNames(lapply(fields, function(f) Reduce(`+`, lapply(parts, `[[`, f))), fields)
}

# Wilson interval on a rejection count — the same interval MCPower reports.
wilson <- function(x, n, z = Z_CRIT) {
  if (n == 0L) return(c(NA_real_, NA_real_))
  p <- x / n; den <- 1 + z^2 / n
  ctr <- (p + z^2 / (2 * n)) / den
  hw  <- z * sqrt(p * (1 - p) / n + z^2 / (4 * n^2)) / den
  c(ctr - hw, ctr + hw)
}

# Engine joint Wald rate (its own draw stream, n_sims = K) for one df_method.
joint_engine_rate <- function(cell, effect, n, df_method, seed, K) {
  m <- MCPower$new("y ~ x + z + (1|g)", family = cell$family)
  m$set_effects(sprintf("x=%g, z=%g", effect, effect))
  m$set_cluster("g", ICC = cell$icc, n_clusters = cell$g, cluster_level_vars = "z")
  r <- m$find_power(sample_size = n, target_test = "x, z", n_sims = K, seed = seed,
                    df_method = df_method, verbose = FALSE, progress_callback = FALSE)
  r$estimator_extras$joint_uncorrected_rate
}

